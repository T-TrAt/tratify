import { expect, test } from '@playwright/test'

test('Material properties, source edits, events and reset work in the shared three-pane editor', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/component-docs/material-button')
  const playground = page.getByTestId('material-playground')
  const configuration = page.getByRole('region', { name: 'MButton 配置', exact: true })
  const frame = page.frameLocator('.vue-repl iframe')
  await expect(frame.locator('m-button')).toHaveCount(1)
  await expect(frame.getByRole('button', { name: '按钮', exact: true })).toBeVisible()
  await expect(configuration.getByRole('combobox', { name: 'variant', exact: true })).toHaveText('filled')
  await expect(configuration.getByRole('combobox', { name: 'size', exact: true })).toHaveText('s')
  await expect(configuration.getByRole('combobox', { name: 'shape', exact: true })).toHaveText('round')
  await configuration.getByRole('combobox', { name: 'variant', exact: true }).click()
  await page.getByRole('option', { name: 'outlined', exact: true }).click()
  await expect(frame.locator('m-button').first().getByRole('button')).toHaveClass(/mtrl-button--outlined/)
  await configuration.getByRole('combobox', { name: 'size', exact: true }).click()
  await page.getByRole('option', { name: 'l', exact: true }).click()
  await configuration.getByRole('combobox', { name: 'shape', exact: true }).click()
  await page.getByRole('option', { name: 'square', exact: true }).click()
  await expect(frame.locator('m-button').getByRole('button')).toHaveClass(/mtrl-button--l/)
  await expect(frame.locator('m-button').getByRole('button')).toHaveClass(/mtrl-button--square/)
  await configuration.getByRole('switch', { name: 'disabled', exact: true }).check()
  await expect(frame.locator('m-button').getByRole('button')).toBeDisabled()
  await configuration.getByRole('switch', { name: 'disabled', exact: true }).uncheck()
  await configuration.getByRole('textbox', { name: 'label', exact: true }).fill('低代码按钮')
  await expect(frame.getByRole('button', { name: '低代码按钮', exact: true }).first()).toBeVisible()
  await frame.getByRole('button', { name: '低代码按钮', exact: true }).first().click()
  await expect(frame.getByRole('textbox', { name: '事件记录内容', exact: true })).toHaveValue(/click/)
  await playground.getByRole('button', { name: '复制当前文件', exact: true }).click()
  const source = await page.evaluate(() => navigator.clipboard.readText())
  expect(source).toContain('低代码按钮')
  expect(source).toContain('outlined')
  await playground.getByRole('tab', { name: 'App.vue', exact: true }).click()
  await expect(playground.locator('.source-pane .CodeMirror')).toBeVisible()
  await playground.locator('.source-pane .CodeMirror').evaluate((el, source) => {
    const editor = (el as HTMLElement & { CodeMirror: { setValue(value: string): void } }).CodeMirror
    editor.setValue(source.replaceAll('低代码按钮', '源码按钮'))
  }, source)
  await expect(frame.getByRole('button', { name: '源码按钮', exact: true }).first()).toBeVisible()
  await playground.getByRole('button', { name: '重新运行', exact: true }).click()
  await expect(frame.getByRole('button', { name: '源码按钮', exact: true }).first()).toBeVisible()
  await playground.getByRole('button', { name: '恢复当前配置', exact: true }).click()
  await expect(frame.getByRole('button', { name: '按钮', exact: true })).toBeVisible()
  await expect(frame.locator('m-button')).toHaveCount(1)
  await expect(frame.locator('m-button').getByRole('button')).toHaveClass(/mtrl-button--filled/)
  await expect(frame.locator('m-button').getByRole('button')).toHaveClass(/mtrl-button--s(?:\s|$)/)
  await playground.getByRole('tab', { name: '低代码', exact: true }).click()
  await expect(configuration.getByRole('textbox', { name: 'label', exact: true })).toHaveValue('按钮')
})

test('Material model overrides and native interactions use the same live state', async ({ page }) => {
  await page.goto('/component-docs/material-select')
  const configuration = page.getByRole('region', { name: 'MSelect 配置', exact: true })
  const frame = page.frameLocator('.vue-repl iframe')
  await expect(frame.getByRole('combobox', { name: '目的地', exact: true })).toHaveValue('上海')
  await configuration.getByRole('checkbox', { name: '使用 modelValue', exact: true }).check()
  await configuration.getByRole('textbox', { name: 'modelValue', exact: true }).fill('"hangzhou"')
  await expect(frame.getByRole('combobox', { name: '目的地', exact: true })).toHaveValue('杭州')
  await frame.getByRole('combobox', { name: '目的地', exact: true }).focus()
  await frame.getByRole('combobox', { name: '目的地', exact: true }).press('ArrowDown')
  await frame.getByRole('option', { name: '成都', exact: true }).click()
  await expect(frame.getByRole('combobox', { name: '目的地', exact: true })).toHaveValue('成都')
  await expect(frame.getByRole('textbox', { name: '事件记录内容', exact: true })).toHaveValue(/update:modelValue.*chengdu/)
})

test('Material slot controls compile HTML and invalid numeric configuration preserves the last preview', async ({ page }) => {
  await page.goto('/component-docs/material-card')
  const configuration = page.getByRole('region', { name: 'MCard 配置', exact: true })
  const frame = page.frameLocator('.vue-repl iframe')
  await expect(frame.getByAltText('湖畔山景')).toBeVisible()
  await expect.poll(() => frame.getByAltText('湖畔山景').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await configuration.getByRole('button', { name: '插槽', exact: true }).click()
  await configuration.getByRole('switch', { name: '自定义 actions', exact: true }).check()
  await configuration.getByRole('textbox', { name: 'actions 模板', exact: true }).fill('<button type="button">自定义卡片操作</button>')
  await expect(frame.getByRole('button', { name: '自定义卡片操作', exact: true })).toBeVisible()
  await page.goto('/component-docs/material-slider')
  const sliderConfig = page.getByRole('region', { name: 'MSlider 配置', exact: true })
  await expect(frame.getByRole('slider', { name: '音量', exact: true })).toHaveAttribute('aria-valuenow', '65')
  await sliderConfig.getByRole('textbox', { name: 'min', exact: true }).fill('bad')
  await expect(sliderConfig.getByRole('alert').filter({ hasText: '配置有误' })).toContainText('请修正')
  await expect(frame.getByRole('slider', { name: '音量', exact: true })).toHaveAttribute('aria-valuenow', '65')
  await sliderConfig.getByRole('textbox', { name: 'min', exact: true }).fill('10')
  await expect(sliderConfig.getByRole('alert')).toHaveCount(0)
  await expect(frame.getByRole('slider', { name: '音量', exact: true })).toHaveAttribute('aria-valuemin', '10')
})

